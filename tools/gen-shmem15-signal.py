#!/usr/bin/env python3
"""Generate src/shmem15-signal.h: the OpenSHMEM 1.5/1.6 signaling declarations and the C11
type-generic bindings of put_signal / put_signal_nbi (with an optional leading context) and
signal_add / signal_set (with an optional leading context).

Usage: tools/gen-shmem15-signal.py > src/shmem15-signal.h

Like tools/gen-c11-generics.py, selection is on the basic C types only: the fixed-width, size_t
and ptrdiff_t types alias a basic type on every platform, and duplicate _Generic associations
are an error."""

BASIC = [('float','float'),('double','double'),('longdouble','long double'),('char','char'),
         ('schar','signed char'),('short','short'),('int','int'),('long','long'),
         ('longlong','long long'),('uchar','unsigned char'),('ushort','unsigned short'),
         ('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long')]

out = []
w = out.append
w('''/* Generated by tools/gen-shmem15-signal.py; do not edit.
 *
 * OpenSHMEM 1.5/1.6 signaling: put-with-signal, signal add / set / fetch and
 * signal wait.  Included from shmem.h (through shmem15.h), inside its extern "C" block,
 * after shmem14.h, whose type tables it uses. */

#ifndef OSHMPI_SHMEM15_SIGNAL_H
#define OSHMPI_SHMEM15_SIGNAL_H

#include <stddef.h>
#include <stdint.h>

/* signal operators */
#define SHMEM_SIGNAL_SET 0
#define SHMEM_SIGNAL_ADD 1

/* put-with-signal for every standard RMA type, with and without a context */
#define OSHMPI_DECL_PUT_SIGNAL(N, T)                                                           \\
    void shmem_##N##_put_signal(T *dest, const T *source, size_t nelems, uint64_t *sig_addr,   \\
                                uint64_t signal, int sig_op, int pe);                          \\
    void shmem_##N##_put_signal_nbi(T *dest, const T *source, size_t nelems,                   \\
                                    uint64_t *sig_addr, uint64_t signal, int sig_op, int pe);  \\
    void shmem_ctx_##N##_put_signal(shmem_ctx_t ctx, T *dest, const T *source, size_t nelems,  \\
                                    uint64_t *sig_addr, uint64_t signal, int sig_op, int pe);  \\
    void shmem_ctx_##N##_put_signal_nbi(shmem_ctx_t ctx, T *dest, const T *source,            \\
                                        size_t nelems, uint64_t *sig_addr, uint64_t signal,    \\
                                        int sig_op, int pe);

OSHMPI_RMA_TYPES(OSHMPI_DECL_PUT_SIGNAL)

/* bytes and the sized forms (8, 16, 32, 64 and 128 bits) */
#define OSHMPI_DECL_PUT_SIGNAL_SIZED(S)                                                        \\
    void shmem_put##S##_signal(void *dest, const void *source, size_t nelems,                  \\
                               uint64_t *sig_addr, uint64_t signal, int sig_op, int pe);       \\
    void shmem_put##S##_signal_nbi(void *dest, const void *source, size_t nelems,              \\
                                   uint64_t *sig_addr, uint64_t signal, int sig_op, int pe);   \\
    void shmem_ctx_put##S##_signal(shmem_ctx_t ctx, void *dest, const void *source,            \\
                                   size_t nelems, uint64_t *sig_addr, uint64_t signal,         \\
                                   int sig_op, int pe);                                        \\
    void shmem_ctx_put##S##_signal_nbi(shmem_ctx_t ctx, void *dest, const void *source,        \\
                                       size_t nelems, uint64_t *sig_addr, uint64_t signal,     \\
                                       int sig_op, int pe);

OSHMPI_DECL_PUT_SIGNAL_SIZED(mem)
OSHMPI_DECL_PUT_SIGNAL_SIZED(8)
OSHMPI_DECL_PUT_SIGNAL_SIZED(16)
OSHMPI_DECL_PUT_SIGNAL_SIZED(32)
OSHMPI_DECL_PUT_SIGNAL_SIZED(64)
OSHMPI_DECL_PUT_SIGNAL_SIZED(128)

void     shmem_signal_add(uint64_t *sig_addr, uint64_t signal, int pe);
void     shmem_ctx_signal_add(shmem_ctx_t ctx, uint64_t *sig_addr, uint64_t signal, int pe);
void     shmem_signal_set(uint64_t *sig_addr, uint64_t signal, int pe);
void     shmem_ctx_signal_set(shmem_ctx_t ctx, uint64_t *sig_addr, uint64_t signal, int pe);
uint64_t shmem_signal_fetch(const uint64_t *sig_addr);
uint64_t shmem_signal_wait_until(uint64_t *sig_addr, int cmp, uint64_t cmp_value);

/* the names these had as extensions before they were standardized */
void     shmemx_signal_add(uint64_t *sig_addr, uint64_t signal, int pe);
void     shmemx_signal_set(uint64_t *sig_addr, uint64_t signal, int pe);

#if (!defined(__cplusplus) && !defined(SHMEM_INTERNAL_INCLUDE))

/* C11 type-generic bindings.  The argument count chooses between the default-context form and
 * the form with a leading context: k arguments -> default context, k + 1 -> context. */
#define OSHMPI_SIGPICK_3(_1, _2, _3, _4, NAME, ...) NAME
#define OSHMPI_SIGPICK_7(_1, _2, _3, _4, _5, _6, _7, _8, NAME, ...) NAME

#define shmem_signal_add(...) \\
    OSHMPI_SIGPICK_3(__VA_ARGS__, shmem_ctx_signal_add, shmem_signal_add, 0)(__VA_ARGS__)
#define shmem_signal_set(...) \\
    OSHMPI_SIGPICK_3(__VA_ARGS__, shmem_ctx_signal_set, shmem_signal_set, 0)(__VA_ARGS__)
#define shmemx_signal_add(...) \\
    OSHMPI_SIGPICK_3(__VA_ARGS__, shmem_ctx_signal_add, shmemx_signal_add, 0)(__VA_ARGS__)
#define shmemx_signal_set(...) \\
    OSHMPI_SIGPICK_3(__VA_ARGS__, shmem_ctx_signal_set, shmemx_signal_set, 0)(__VA_ARGS__)
''')
for op, suffix in (('put_signal',''), ('put_signal_nbi','_nbi')):
    for ctx in (False, True):
        pre = 'shmem_ctx_' if ctx else 'shmem_'
        params = ('ctx, ' if ctx else '') + 'dest, source, nelems, sig_addr, signal, sig_op, pe'
        lines = ', \\\n'.join('             %s *: %s%s_%s' % (t, pre, n, op) for n, t in BASIC)
        w('#define OSHMPI_G_%s_%s(%s) \\\n    _Generic(&(dest)[0], \\\n%s \\\n            )(%s)\n' %
          (op, 'CTX' if ctx else 'NOCTX', params, lines, params))
    w('#define shmem_%s(...) \\\n    OSHMPI_SIGPICK_7(__VA_ARGS__, OSHMPI_G_%s_CTX, OSHMPI_G_%s_NOCTX, 0)(__VA_ARGS__)\n' % (op, op, op))
w('''
#endif /* !__cplusplus && !SHMEM_INTERNAL_INCLUDE */

#endif /* OSHMPI_SHMEM15_SIGNAL_H */''')
print('\n'.join(out))
