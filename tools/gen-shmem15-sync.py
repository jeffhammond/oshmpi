#!/usr/bin/env python3
"""Generate src/shmem15-sync.h: the OpenSHMEM 1.5 wait_until_{all,any,some} and
test_{all,any,some} routines (plain and _vector forms), their prototypes for every
point-to-point synchronization type and their C11 type-generic bindings.

Selection is on the basic C types only (the fixed-width, size_t and ptrdiff_t types alias
a basic type, and duplicate _Generic associations are an error), as in
tools/gen-c11-generics.py.

Usage: tools/gen-shmem15-sync.py > src/shmem15-sync.h
"""

BASIC = [('short', 'short'), ('int', 'int'), ('long', 'long'), ('longlong', 'long long'),
         ('ushort', 'unsigned short'), ('uint', 'unsigned int'), ('ulong', 'unsigned long'),
         ('ulonglong', 'unsigned long long')]

# (name, return type, extra output arguments before status)
FAMILIES = [
    ('wait_until_all', 'void', ''),
    ('wait_until_any', 'size_t', ''),
    ('wait_until_some', 'size_t', 'size_t *indices, '),
    ('test_all', 'int', ''),
    ('test_any', 'size_t', ''),
    ('test_some', 'size_t', 'size_t *indices, '),
]

out = []
w = out.append
w('''/* OpenSHMEM 1.5: point-to-point synchronization on arrays of variables.
 * Generated by tools/gen-shmem15-sync.py; do not edit.
 * Included from shmem.h inside its extern "C" block, after shmem14.h. */

#ifndef OSHMPI_SHMEM15_SYNC_H
#define OSHMPI_SHMEM15_SYNC_H

#include <stddef.h>
#include <stdint.h>

''')

w('/* Typed routines: shmem_<TYPENAME>_{wait_until,test}_{all,any,some}[_vector]. */\n')
w('#define OSHMPI_DECL_SYNC15(N, T) \\\n')
decls = []
for name, ret, extra in FAMILIES:
    decls.append('    %s shmem_##N##_%s(T *ivars, size_t nelems, %sconst int *status, int cmp, T cmp_value);'
                 % (ret, name, extra))
    decls.append('    %s shmem_##N##_%s_vector(T *ivars, size_t nelems, %sconst int *status, int cmp, const T *cmp_values);'
                 % (ret, name, extra))
w(' \\\n'.join(decls) + '\n\n')
w('OSHMPI_SYNC_TYPES(OSHMPI_DECL_SYNC15)\n\n')

w('/* C11 type-generic bindings (as for the 1.4 ones, not in C++ and not inside the library). */\n')
w('#if (!defined(__cplusplus) && !defined(SHMEM_INTERNAL_INCLUDE))\n')
for name, ret, extra in FAMILIES:
    for vec in (False, True):
        fn = name + ('_vector' if vec else '')
        args = ['ivars', 'nelems'] + (['indices'] if extra else []) + ['status', 'cmp', 'cmp_values' if vec else 'cmp_value']
        a = ', '.join(args)
        lines = []
        for n, t in BASIC:
            for q in ('volatile ', ''):
                lines.append('             %s%s *: shmem_%s_%s' % (q, t, n, fn))
        w('#define shmem_%s(%s) \\\n    _Generic(&(ivars)[0], \\\n%s \\\n            )(%s)\n' % (fn, a, ', \\\n'.join(lines), a))
w('#endif /* generics */\n\n#endif /* OSHMPI_SHMEM15_SYNC_H */\n')
print(''.join(out), end='')
