#!/usr/bin/env python3
"""Generate src/shmem14-generic.h: the OpenSHMEM 1.4 C11 type-generic bindings.

Selection is on the basic C types only: the fixed-width, size_t and ptrdiff_t types
alias a basic type on every platform (and duplicate _Generic associations are an
error), so this covers them all.  Each macro also has a context form with the
context as its first argument, chosen by argument count.

Usage: tools/gen-c11-generics.py > src/shmem14-generic.h
"""

RMA   = [('float','float'),('double','double'),('longdouble','long double'),('char','char'),
         ('schar','signed char'),('short','short'),('int','int'),('long','long'),
         ('longlong','long long'),('uchar','unsigned char'),('ushort','unsigned short'),
         ('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long')]
AMO   = [('int','int'),('long','long'),('longlong','long long'),
         ('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long')]
EXT   = AMO + [('float','float'),('double','double')]
BIT   = [('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long')]
SYNC  = [('short','short'),('int','int'),('long','long'),('longlong','long long'),
         ('ushort','unsigned short'),('uint','unsigned int'),('ulong','unsigned long'),
         ('ulonglong','unsigned long long')]

# (generic name, function suffix, noctx arg names, type table, qualifiers of the pointer arg)
OPS = [
 ('put','put',['dest','source','nelems','pe'],RMA,['']),
 ('get','get',['dest','source','nelems','pe'],RMA,['']),
 ('put_nbi','put_nbi',['dest','source','nelems','pe'],RMA,['']),
 ('get_nbi','get_nbi',['dest','source','nelems','pe'],RMA,['']),
 ('iput','iput',['dest','source','dst','sst','nelems','pe'],RMA,['']),
 ('iget','iget',['dest','source','dst','sst','nelems','pe'],RMA,['']),
 ('p','p',['dest','value','pe'],RMA,['']),
 ('g','g',['src','pe'],RMA,['','const ']),
 ('atomic_fetch','atomic_fetch',['src','pe'],EXT,['','const ']),
 ('atomic_set','atomic_set',['dest','value','pe'],EXT,['']),
 ('atomic_swap','atomic_swap',['dest','value','pe'],EXT,['']),
 ('atomic_compare_swap','atomic_compare_swap',['dest','cond','value','pe'],AMO,['']),
 ('atomic_fetch_inc','atomic_fetch_inc',['dest','pe'],AMO,['']),
 ('atomic_inc','atomic_inc',['dest','pe'],AMO,['']),
 ('atomic_fetch_add','atomic_fetch_add',['dest','value','pe'],AMO,['']),
 ('atomic_add','atomic_add',['dest','value','pe'],AMO,['']),
 ('atomic_fetch_and','atomic_fetch_and',['dest','value','pe'],BIT,['']),
 ('atomic_and','atomic_and',['dest','value','pe'],BIT,['']),
 ('atomic_fetch_or','atomic_fetch_or',['dest','value','pe'],BIT,['']),
 ('atomic_or','atomic_or',['dest','value','pe'],BIT,['']),
 ('atomic_fetch_xor','atomic_fetch_xor',['dest','value','pe'],BIT,['']),
 ('atomic_xor','atomic_xor',['dest','value','pe'],BIT,['']),
 ('wait_until','wait_until',['ivar','cmp','cmp_value'],SYNC,['volatile ','']),
 ('test','test',['ivar','cmp','cmp_value'],SYNC,['volatile ','']),
]

def pick(k):
    # chooses NAME by the number of arguments: k args -> noctx, k+1 args -> ctx
    args = ','.join('_%d' % i for i in range(1, k + 2))
    return '#define OSHMPI_PICK_%d(%s,NAME,...) NAME\n' % (k, args)

out = []
out.append('/* Generated by tools/gen-c11-generics.py; do not edit. */\n')
out.append('#ifndef OSHMPI_SHMEM14_GENERIC_H\n#define OSHMPI_SHMEM14_GENERIC_H\n\n')
for k in sorted({len(o[2]) for o in OPS}):
    out.append(pick(k))
out.append('\n')

def assoc(prefix, ctx_prefix, types, quals, kind):
    lines = []
    for n, t in types:
        for q in quals:
            lines.append('             %s%s *: %s_%s_%s' % (q, t, prefix, n, kind))
    return lines

for name, suf, args, types, quals in OPS:
    k = len(args)
    ptr = args[0]
    a = ', '.join(args)
    # no-context form
    lines = [('             %s%s *: shmem_%s_%s' % (q, t, n, suf)) for n, t in types for q in quals]
    out.append('#define OSHMPI_G_%s_NOCTX(%s) \\\n    _Generic(&(%s)[0], \\\n%s \\\n            )(%s)\n' %
               (name, a, ptr, ', \\\n'.join(lines), a))
    # context form: first argument is the context, data pointer is the second
    cargs = ['ctx'] + args
    ca = ', '.join(cargs)
    clines = [('             %s%s *: shmem_ctx_%s_%s' % (q, t, n, suf)) for n, t in types for q in quals]
    out.append('#define OSHMPI_G_%s_CTX(%s) \\\n    _Generic(&(%s)[0], \\\n%s \\\n            )(%s)\n' %
               (name, ca, ptr, ', \\\n'.join(clines), ca))
    out.append('#define shmem_%s(...) \\\n    OSHMPI_PICK_%d(__VA_ARGS__, OSHMPI_G_%s_CTX, OSHMPI_G_%s_NOCTX, 0)(__VA_ARGS__)\n\n' %
               (name, k, name, name))

out.append('#endif /* OSHMPI_SHMEM14_GENERIC_H */\n')
print(''.join(out), end='')
