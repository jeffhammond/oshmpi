#!/usr/bin/env python3
"""Generate the C11 type-generic bindings for the OpenSHMEM 1.5 team collectives and
reductions, and splice them into src/shmem15-team.h between the GENERATED markers.

Selection is on the basic C types only: the fixed-width, size_t and ptrdiff_t types alias a
basic type on every platform (and duplicate _Generic associations are an error).

Usage: tools/gen-shmem15-team.py   (rewrites src/shmem15-team.h in place)
"""
import os, sys

RMA = [('float','float'),('double','double'),('longdouble','long double'),('char','char'),
       ('schar','signed char'),('short','short'),('int','int'),('long','long'),
       ('longlong','long long'),('uchar','unsigned char'),('ushort','unsigned short'),
       ('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long')]
BIT = [('uchar','unsigned char'),('ushort','unsigned short'),('uint','unsigned int'),
       ('ulong','unsigned long'),('ulonglong','unsigned long long')]
MINMAX = BIT + [('char','char'),('schar','signed char'),('short','short'),('int','int'),
                ('long','long'),('longlong','long long'),('float','float'),('double','double'),
                ('longdouble','long double')]
SUMPROD = MINMAX + [('complexd','double _Complex'),('complexf','float _Complex')]

# (generic name, function suffix, arguments, type table)
OPS = [
 ('broadcast','broadcast',['team','dest','source','nelems','PE_root'],RMA),
 ('collect','collect',['team','dest','source','nelems'],RMA),
 ('fcollect','fcollect',['team','dest','source','nelems'],RMA),
 ('alltoall','alltoall',['team','dest','source','nelems'],RMA),
 ('alltoalls','alltoalls',['team','dest','source','dst','sst','nelems'],RMA),
 ('and_reduce','and_reduce',['team','dest','source','nreduce'],BIT),
 ('or_reduce','or_reduce',['team','dest','source','nreduce'],BIT),
 ('xor_reduce','xor_reduce',['team','dest','source','nreduce'],BIT),
 ('max_reduce','max_reduce',['team','dest','source','nreduce'],MINMAX),
 ('min_reduce','min_reduce',['team','dest','source','nreduce'],MINMAX),
 ('sum_reduce','sum_reduce',['team','dest','source','nreduce'],SUMPROD),
 ('prod_reduce','prod_reduce',['team','dest','source','nreduce'],SUMPROD),
]

out = []
for name, suf, args, types in OPS:
    a = ', '.join(args)
    lines = ',  \\\n'.join('             %s *: shmem_%s_%s' % (t, n, suf) for n, t in types)
    out.append('#define shmem_%s(%s) \\\n    _Generic(&(dest)[0],  \\\n%s  \\\n            )(%s)\n' % (name, a, lines, a))
block = '/* BEGIN GENERATED by tools/gen-shmem15-team.py */\n' + '\n'.join(out) + '/* END GENERATED */'

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'shmem15-team.h')
s = open(path).read()
a = s.index('/* BEGIN GENERATED')
b = s.index('/* END GENERATED */') + len('/* END GENERATED */')
open(path, 'w').write(s[:a] + block + s[b:])
