#!/usr/bin/env python3
"""Generate src/shmem15-amo.h: OpenSHMEM 1.5/1.6 nonblocking atomics, malloc with hints and
context sessions.

The declarations of the typed routines come from the type tables in shmem14.h
(OSHMPI_AMO_TYPES, OSHMPI_EXT_AMO_ONLY_TYPES, OSHMPI_BITWISE_AMO_TYPES).  The C11 type-generic
macros select on the basic C types only, as in shmem14-generic.h (the fixed-width, size_t and
ptrdiff_t types alias a basic type, and duplicate _Generic associations are an error).  The
signed bitwise AMOs exist only as int32/int64 functions, so int selects int32 and long/long long
select int64 (long selects int32 where it is 32 bits wide), exactly as in tools/gen-c11-generics.py.

Usage: tools/gen-shmem15-amo.py > src/shmem15-amo.h
"""

STD = [('int','int'),('long','long'),('longlong','long long'),
       ('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long')]
EXT = STD + [('float','float'),('double','double')]
BIT_COMMON = [('uint','unsigned int'),('ulong','unsigned long'),('ulonglong','unsigned long long'),
              ('int32','int'),('int64','long long')]
BIT = BIT_COMMON + [('int64','long')]
BIT_ILP32 = BIT_COMMON + [('int32','long')]

# (operation, argument names without ctx, type table, name of the argument that selects the type,
#  qualifiers of that pointer)
OPS = [
 ('fetch_nbi',        ['fetch','source','pe'],                 EXT, 'source', ['', 'const ']),
 ('swap_nbi',         ['fetch','dest','value','pe'],           EXT, 'dest',   ['']),
 ('compare_swap_nbi', ['fetch','dest','cond','value','pe'],    STD, 'dest',   ['']),
 ('fetch_inc_nbi',    ['fetch','dest','pe'],                   STD, 'dest',   ['']),
 ('fetch_add_nbi',    ['fetch','dest','value','pe'],           STD, 'dest',   ['']),
 ('fetch_and_nbi',    ['fetch','dest','value','pe'],           BIT, 'dest',   ['']),
 ('fetch_or_nbi',     ['fetch','dest','value','pe'],           BIT, 'dest',   ['']),
 ('fetch_xor_nbi',    ['fetch','dest','value','pe'],           BIT, 'dest',   ['']),
]

out = []
w = out.append

w('''/* Generated by tools/gen-shmem15-amo.py; do not edit.
 *
 * OpenSHMEM 1.5/1.6: nonblocking atomics, malloc with hints and context sessions.
 * Included from shmem.h, inside its extern "C" block, after shmem14.h. */

#ifndef OSHMPI_SHMEM15_AMO_H
#define OSHMPI_SHMEM15_AMO_H

#include <stddef.h>
#include <stdint.h>

/* ---- malloc with hints (shmem_malloc_hints) ---------------------------- */

#define SHMEM_MALLOC_ATOMICS_REMOTE (1L<<0)
#define SHMEM_MALLOC_SIGNAL_REMOTE  (1L<<1)

void *shmem_malloc_with_hints(size_t size, long hints);

/* ---- context sessions (shmem_ctx_session_start / shmem_ctx_session_stop) */

typedef struct {
    size_t total_ops;
} shmem_ctx_session_config_t;

#define SHMEM_CTX_SESSION_BATCH     (1L<<0)    /* session option */
#define SHMEM_CTX_SESSION_TOTAL_OPS (1L<<0)    /* configuration mask bit */

void shmem_ctx_session_start(shmem_ctx_t ctx, long options,
                             const shmem_ctx_session_config_t *config, long config_mask);
void shmem_ctx_session_stop(shmem_ctx_t ctx);

/* ---- nonblocking atomics ----------------------------------------------- *
 * The fetched value is valid after a subsequent shmem_quiet / shmem_ctx_quiet. */

#define OSHMPI_DECL_AMO_NBI_FETCH_SWAP(N, T)                                                   \\
    void shmem_ctx_##N##_atomic_fetch_nbi(shmem_ctx_t ctx, T *fetch, const T *source, int pe);  \\
    void shmem_##N##_atomic_fetch_nbi(T *fetch, const T *source, int pe);                       \\
    void shmem_ctx_##N##_atomic_swap_nbi(shmem_ctx_t ctx, T *fetch, T *dest, T value, int pe);  \\
    void shmem_##N##_atomic_swap_nbi(T *fetch, T *dest, T value, int pe);

#define OSHMPI_DECL_AMO_NBI_INT(N, T)                                                          \\
    void shmem_ctx_##N##_atomic_compare_swap_nbi(shmem_ctx_t ctx, T *fetch, T *dest, T cond,   \\
                                                 T value, int pe);                             \\
    void shmem_##N##_atomic_compare_swap_nbi(T *fetch, T *dest, T cond, T value, int pe);      \\
    void shmem_ctx_##N##_atomic_fetch_inc_nbi(shmem_ctx_t ctx, T *fetch, T *dest, int pe);     \\
    void shmem_##N##_atomic_fetch_inc_nbi(T *fetch, T *dest, int pe);                          \\
    void shmem_ctx_##N##_atomic_fetch_add_nbi(shmem_ctx_t ctx, T *fetch, T *dest, T value, int pe); \\
    void shmem_##N##_atomic_fetch_add_nbi(T *fetch, T *dest, T value, int pe);

#define OSHMPI_DECL_AMO_NBI_BITWISE(N, T)                                                      \\
    void shmem_ctx_##N##_atomic_fetch_and_nbi(shmem_ctx_t ctx, T *fetch, T *dest, T value, int pe); \\
    void shmem_##N##_atomic_fetch_and_nbi(T *fetch, T *dest, T value, int pe);                 \\
    void shmem_ctx_##N##_atomic_fetch_or_nbi(shmem_ctx_t ctx, T *fetch, T *dest, T value, int pe);  \\
    void shmem_##N##_atomic_fetch_or_nbi(T *fetch, T *dest, T value, int pe);                  \\
    void shmem_ctx_##N##_atomic_fetch_xor_nbi(shmem_ctx_t ctx, T *fetch, T *dest, T value, int pe); \\
    void shmem_##N##_atomic_fetch_xor_nbi(T *fetch, T *dest, T value, int pe);

OSHMPI_AMO_TYPES(OSHMPI_DECL_AMO_NBI_FETCH_SWAP)
OSHMPI_EXT_AMO_ONLY_TYPES(OSHMPI_DECL_AMO_NBI_FETCH_SWAP)
OSHMPI_AMO_TYPES(OSHMPI_DECL_AMO_NBI_INT)
OSHMPI_BITWISE_AMO_TYPES(OSHMPI_DECL_AMO_NBI_BITWISE)

/* ---- C11 type-generic bindings ------------------------------------------ *
 * Each has an optional leading shmem_ctx_t argument, chosen by argument count. */

#if (!defined(__cplusplus) && !defined(SHMEM_INTERNAL_INCLUDE))

''')

for k in sorted({len(o[1]) for o in OPS}):
    args = ','.join('_%d' % i for i in range(1, k + 2))
    w('#define OSHMPI15_PICK_%d(%s,NAME,...) NAME\n' % (k, args))
w('\n')

def emit(name, args, types, ptr, quals):
    a = ', '.join(args)
    lines = [('             %s%s *: shmem_%s_atomic_%s' % (q, t, n, name)) for n, t in types for q in quals]
    w('#define OSHMPI15_G_%s_NOCTX(%s) \\\n    _Generic(&(%s)[0], \\\n%s \\\n            )(%s)\n' %
      (name, a, ptr, ', \\\n'.join(lines), a))
    ca = ', '.join(['ctx'] + args)
    clines = [('             %s%s *: shmem_ctx_%s_atomic_%s' % (q, t, n, name)) for n, t in types for q in quals]
    w('#define OSHMPI15_G_%s_CTX(%s) \\\n    _Generic(&(%s)[0], \\\n%s \\\n            )(%s)\n' %
      (name, ca, ptr, ', \\\n'.join(clines), ca))

for name, args, types, ptr, quals in OPS:
    k = len(args)
    if types is BIT:
        w('#if __SIZEOF_LONG__ == 8\n')
        emit(name, args, BIT, ptr, quals)
        w('#else\n')
        emit(name, args, BIT_ILP32, ptr, quals)
        w('#endif\n')
    else:
        emit(name, args, types, ptr, quals)
    w('#define shmem_atomic_%s(...) \\\n    OSHMPI15_PICK_%d(__VA_ARGS__, OSHMPI15_G_%s_CTX, OSHMPI15_G_%s_NOCTX, 0)(__VA_ARGS__)\n\n' %
      (name, k, name, name))

w('#endif /* C11 generics */\n\n#endif /* OSHMPI_SHMEM15_AMO_H */\n')
print(''.join(out), end='')
